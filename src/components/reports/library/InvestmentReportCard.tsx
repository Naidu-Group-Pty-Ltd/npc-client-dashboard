import { useState } from 'react';
import { format } from 'date-fns';
import {
  Building2,
  Calendar,
  Download,
  Eye,
  Globe,
  Home,
  Layers3,
  Map,
  MapPin,
  TrendingUp,
  User,
  Zap,
  Loader2,
} from 'lucide-react';
import { toast } from 'sonner';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardFooter, CardHeader } from '@/components/ui/card';
import { RegenerateReportButton } from '@/components/reports/RegenerateReportButton';
import { type ReportTier } from '@/components/reports/TierBadge';
import { resolveCardInvestmentGrade } from '@/components/reports/report-view/utils';
import type { InvestmentReport } from './types';
import { normalizeComparableReportType, REPORT_TYPE_CONFIG, resolveInvestmentReportType, type ReportVariant } from '@/lib/reports/reportVariants';
import { ReportTypeBadge } from '@/components/reports/ReportTypeBadge';
import { downloadClientPdf } from '@/lib/reports/clientPdfDownload';
import { InvestmentGradeSummary } from './InvestmentGradeSummary';
import { resolveReportAddress } from '@/lib/reports/reportAddress';

interface InvestmentReportCardProps {
  report: InvestmentReport;
  /**
   * Every report for the same property, where the caller knows them. The
   * Investment Grade is resolved across these — see `gradeReports` below.
   */
  siblingReports?: InvestmentReport[];
  isSelected: boolean;
  canAddMore: boolean;
  comparisonSelectable: boolean;
  activeComparisonType: ReportVariant | null;
  isAutoGenerated: boolean;
  generatingTier: ReportTier | null;
  canEditReports: boolean;
  generatorLabel: (id?: string | null) => string;
  getGradeColor: (grade: string) => string;
  getScoreColor: (score: number) => string;
  onToggleSelection: (report: InvestmentReport, checked: boolean) => void;
  onView: (report: InvestmentReport) => void;
  onDownload: (report: InvestmentReport) => void;
  onRegenerated: () => void;
  onViewHistory: (report: InvestmentReport) => void;
  onToggleArchive: (report: InvestmentReport) => void;
  onGenerateTier: (report: InvestmentReport, targetTier: ReportTier) => void;
}

const scopeMeta = {
  address: { label: 'Property Analysis', icon: Home, className: 'bg-info/15 text-info hover:bg-info/20 dark:bg-info/30 dark:text-info' },
  suburb: { label: 'Suburb Analysis', icon: Building2, className: 'bg-success/15 text-success hover:bg-success/20 dark:bg-success/30 dark:text-success' },
  zipcode: { label: 'Postcode Analysis', icon: Map, className: 'bg-brand-100 text-brand-700 hover:bg-brand-200 dark:bg-brand-900/30 dark:text-brand-300' },
  state: { label: 'State Analysis', icon: Globe, className: 'bg-accent/15 text-accent hover:bg-accent/20 dark:bg-accent/30 dark:text-accent' },
} as const;

export function InvestmentReportCard({
  report,
  siblingReports,
  isSelected,
  canAddMore,
  comparisonSelectable,
  activeComparisonType,
  isAutoGenerated,
  generatingTier,
  canEditReports,
  generatorLabel,
  getGradeColor,
  getScoreColor,
  onToggleSelection,
  onView,
  onDownload,
  onRegenerated,
  onViewHistory,
  onToggleArchive,
  onGenerateTier,
}: InvestmentReportCardProps) {
  const fullAddress = resolveReportAddress(report);
  const [isDownloadingClientPdf, setIsDownloadingClientPdf] = useState(false);
  const scope = report.report_scope && report.report_scope in scopeMeta
    ? scopeMeta[report.report_scope as keyof typeof scopeMeta]
    : null;
  const ScopeIcon = scope?.icon;
  /**
   * The Investment Grade is a judgement about the PROPERTY, not about the
   * document being looked at — so resolving it and deciding whether to draw it
   * are one answer, in `resolveCardInvestmentGrade`. See its header: the two
   * halves used to live apart, which is why fixing either one alone changed
   * nothing on screen.
   */
  const gradeReports = siblingReports && siblingReports.length > 0 ? siblingReports : [report];
  const { grade: resolvedGrade, show: showGrade, borrowedFromReportId } =
    resolveCardInvestmentGrade(report as any, gradeReports as any);
  const gradeSourceLabel = borrowedFromReportId
    ? (() => {
        const source = gradeReports.find((r) => r.id === borrowedFromReportId);
        const sourceType = source ? normalizeComparableReportType(source) : null;
        return sourceType ? REPORT_TYPE_CONFIG[sourceType].label : null;
      })()
    : null;
  const hasAreaPlaceholder = !report.investment_score && ['suburb', 'zipcode', 'state'].includes(report.report_scope || '');
  const reportType = resolveInvestmentReportType(report);
  const comparableType = normalizeComparableReportType(report);
  const typeLabel = comparableType ? REPORT_TYPE_CONFIG[comparableType].label : 'This';
  const comparisonDisabled = !isSelected && (!comparisonSelectable || !canAddMore);
  const disabledReason = activeComparisonType && comparableType !== activeComparisonType
    ? `Only ${REPORT_TYPE_CONFIG[activeComparisonType].label} reports can be added to this comparison.`
    : !canAddMore ? 'The comparison selection has reached its maximum.' : 'This report is unavailable for comparison.';
  const handleClientPdfDownload = async () => {
    if (isDownloadingClientPdf) return;
    setIsDownloadingClientPdf(true);
    try {
      await downloadClientPdf(report.id, { report: { ...report, report_variant: report.report_variant || reportType } });
      toast.success('Client PDF downloaded successfully.');
    } catch (error) {
      console.error('Client PDF download failed', { reportId: report.id, error });
      toast.error(error instanceof Error ? error.message : 'Client PDF could not be retrieved. Please try again.');
    } finally {
      setIsDownloadingClientPdf(false);
    }
  };

  return (
    <Card
      className={`group relative overflow-hidden rounded-2xl border bg-card/90 shadow-sm transition-all duration-300 hover:-translate-y-0.5 hover:border-primary/30 hover:shadow-xl hover:shadow-primary/10 dark:bg-background/70 ${
        isSelected ? 'border-brand-400/60 ring-2 ring-brand-400/25 shadow-lg shadow-brand-500/10' : 'border-border/70'
      }`}
    >
      <div className="pointer-events-none absolute -right-14 -top-16 h-44 w-44 rounded-full bg-brand-400/10 blur-3xl opacity-0 transition-opacity group-hover:opacity-100" />

      <CardHeader className="relative space-y-4 p-4 pb-3">
        <div className="flex items-start justify-between gap-3">
          <div className="flex min-w-0 flex-1 items-center gap-2">
            <div className="shrink-0" title={comparisonDisabled ? disabledReason : undefined}>
              <Button
                type="button"
                variant="outline"
                size="icon"
                disabled={comparisonDisabled}
                aria-pressed={isSelected}
                aria-label={isSelected ? `Remove ${typeLabel} report for ${fullAddress} from comparison` : comparisonDisabled ? `${typeLabel} report cannot be selected because this comparison contains ${activeComparisonType ? REPORT_TYPE_CONFIG[activeComparisonType].label : 'other'} reports` : `Select ${typeLabel} report for ${fullAddress} for comparison`}
                aria-describedby={comparisonDisabled ? `comparison-reason-${report.id}` : undefined}
                onClick={() => onToggleSelection(report, !isSelected)}
                className={`h-11 w-11 rounded-xl border-2 shadow-sm transition-all focus-visible:ring-2 focus-visible:ring-primary focus-visible:ring-offset-2 ${isSelected ? 'border-primary bg-primary text-primary-foreground hover:bg-primary/90' : comparisonDisabled ? 'cursor-not-allowed border-muted-foreground/30 bg-muted/40 text-muted-foreground opacity-70' : 'border-primary/65 bg-primary/10 text-primary hover:scale-105 hover:border-primary hover:bg-primary/20'}`}
              >
                <span aria-hidden="true" className="text-lg font-bold">{isSelected ? '✓' : comparisonDisabled ? '—' : '+'}</span>
              </Button>
              {comparisonDisabled && <span id={`comparison-reason-${report.id}`} className="sr-only">{disabledReason}</span>}
            </div>
            <div className="flex min-w-0 flex-wrap items-center gap-2">
              {scope && ScopeIcon && (
                <Badge variant="secondary" className={`w-fit gap-1 text-xs ${scope.className}`}>
                  <ScopeIcon className="h-3 w-3" />
                  {scope.label}
                </Badge>
              )}
              <ReportTypeBadge type={reportType} />
            </div>
          </div>

          <div className="flex shrink-0 items-center gap-2">
            {isAutoGenerated && (
              <Badge variant="secondary" className="gap-1 bg-accent/15 text-xs text-accent hover:bg-accent/20 dark:bg-accent/30 dark:text-accent">
                <Zap className="h-3 w-3" />
                Auto
              </Badge>
            )}
            {report.status && report.status !== 'completed' && (
              <Badge variant="outline" className="text-xs capitalize">
                {report.status}
              </Badge>
            )}
          </div>
        </div>

        <div className="space-y-3">
          <div className="flex items-start gap-3">
            <div className="mt-0.5 rounded-xl border border-border/60 bg-background/70 p-2 text-brand-600 dark:text-brand-300">
              <MapPin className="h-4 w-4" />
            </div>
            <div className="min-w-0 flex-1">
              <h3 className="break-words text-lg font-semibold leading-snug tracking-tight text-foreground" title={fullAddress}>
                {fullAddress}
              </h3>
              <div className="mt-2 grid gap-1.5 text-xs text-muted-foreground sm:grid-cols-2">
                <span className="flex items-center gap-1.5">
                  <Calendar className="h-3.5 w-3.5" />
                  {format(new Date(report.created_at), 'PPp')}
                </span>
                <span className="flex items-center gap-1.5">
                  <User className="h-3.5 w-3.5" />
                  {generatorLabel(report.generated_by)}
                </span>
                <span className="flex items-center gap-1.5">
                  <Layers3 className="h-3.5 w-3.5" />
                  Version {report.current_version || 1}
                </span>
              </div>
            </div>
          </div>
        </div>
      </CardHeader>

      <CardContent className="relative space-y-4 px-4 pb-4">
        {showGrade ? (
          <InvestmentGradeSummary grade={resolvedGrade} sourceLabel={gradeSourceLabel} />
        ) : hasAreaPlaceholder ? (
          <div className="rounded-2xl border border-dashed border-border/70 bg-muted/25 p-3">
            <div className="flex items-center gap-3">
              <div className="flex h-12 w-12 items-center justify-center rounded-2xl bg-muted text-muted-foreground">
                <Map className="h-5 w-5" />
              </div>
              <div>
                <div className="text-sm font-semibold text-foreground">Area Score Pending</div>
                <p className="text-xs text-muted-foreground">Generate a new report to calculate area score</p>
              </div>
            </div>
          </div>
        ) : null}
      </CardContent>

      <CardFooter className="relative flex flex-col gap-2 border-t border-border/60 bg-muted/20 p-4">
        <div className="flex w-full flex-wrap gap-2 sm:flex-nowrap">
          <Button variant="default" size="sm" onClick={() => onView(report)} className="flex-1 gap-1.5 rounded-xl">
            <Eye className="h-3.5 w-3.5" />
            View
          </Button>
          <Button variant="outline" size="sm" onClick={handleClientPdfDownload} disabled={isDownloadingClientPdf} className="flex-1 gap-1.5 rounded-xl border-primary/40 hover:border-primary hover:bg-primary/10" aria-label={`Download client PDF for ${fullAddress}`} title="Download Client PDF">
            {isDownloadingClientPdf ? <Loader2 className="h-3.5 w-3.5 animate-spin" /> : <Download className="h-3.5 w-3.5" />}
            <span className="sm:hidden">Client PDF</span><span className="hidden sm:inline">{isDownloadingClientPdf ? 'Preparing…' : 'Download Client PDF'}</span>
          </Button>
        </div>
        <RegenerateReportButton
          reportId={report.id}
          propertyAddress={fullAddress}
          onRegenerated={onRegenerated}
          variant="ghost"
          size="sm"
          className="w-full justify-center rounded-xl"
        />
        {/* PDF download is available inside the report viewer (View) to avoid loading huge report payloads in the list. */}
      </CardFooter>
    </Card>
  );
}
